#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd -- "$script_dir/../../.." && pwd)"
blender_bin="${BLENDER_BIN:-blender}"
output_dir="$repo_root/public/art/v3/gate-bridge"
raw_glb="$output_dir/gate-bridge.raw.glb"
final_glb="$output_dir/gate-bridge.glb"
report_json="$output_dir/gate-bridge.report.json"
blend_file="$repo_root/art/blender/gate_bridge_vertical_slice.blend"
dedup_glb="$output_dir/.gate-bridge.dedup.glb"

mkdir -p "$output_dir"

"$blender_bin" --background --factory-startup \
  --python "$repo_root/art/blender/gate_bridge_vertical_slice.py" -- \
  --output "$raw_glb" \
  --blend "$blend_file"

if [[ ! -s "$raw_glb" ]]; then
  echo "Blender did not produce $raw_glb" >&2
  exit 1
fi

# Use only hierarchy-safe transforms. The generic `optimize` preset intentionally
# flattens and joins nodes, which would destroy the stable LOD/socket contract.
# Version pinning keeps generated bytes reproducible across authoring machines.
npx --yes @gltf-transform/cli@4.2.1 dedup "$raw_glb" "$dedup_glb"
npx --yes @gltf-transform/cli@4.2.1 meshopt \
  "$dedup_glb" "$final_glb" \
  --level high \
  --quantization-volume mesh \
  --quantize-color 8 \
  --quantize-normal 10 \
  --quantize-position 14

node "$repo_root/scripts/art/v3/inspect-gate-bridge.mjs" \
  "$final_glb" --json "$report_json"

for generated_intermediate in "$raw_glb" "$dedup_glb"; do
  if [[ -f "$generated_intermediate" ]]; then
    unlink "$generated_intermediate"
  fi
done
